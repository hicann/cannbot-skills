def _scp_push_dir(local_dir: Path, a3_user: str, a3_host: str, remote_dir: str) -> Optional[str]:
    """Tar local_dir, scp to A3, extract at remote_dir. Returns None on success
    or error string."""
    import tempfile
    with tempfile.NamedTemporaryFile(suffix=".tar.gz", delete=False) as tf:
        tar_path = Path(tf.name)
    try:
        rc = subprocess.call(
            ["tar", "czf", str(tar_path), "-C", str(local_dir.parent), local_dir.name],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        )
        if rc != 0:
            return f"tar exited {rc}"
        remote_parent = remote_dir.rsplit("/", 1)[0]
        scp_target = f"{a3_user}@{a3_host}:/tmp/{tar_path.name}"
        rc = subprocess.call(
            ["scp", "-q", "-o", "StrictHostKeyChecking=no",
             "-o", "UserKnownHostsFile=/dev/null",
             str(tar_path), scp_target],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        )
        if rc != 0:
            return f"scp push exited {rc}"
        # Extract on remote (overwrites)
        rc = subprocess.call(
            ["ssh", "-o", "StrictHostKeyChecking=no",
             "-o", "UserKnownHostsFile=/dev/null",
             f"{a3_user}@{a3_host}",
             f"mkdir -p '{remote_parent}' && rm -rf '{remote_dir}' && "
             f"tar xzf /tmp/{tar_path.name} -C '{remote_parent}' && "
             f"rm -f /tmp/{tar_path.name}"],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        )
        if rc != 0:
            return f"remote extract exited {rc}"
        return None
    finally:
        tar_path.unlink(missing_ok=True)


def _scp_pull_files(
    a3_user: str, a3_host: str, remote_dir: str,
    filenames: list, local_dir: Path,
) -> Optional[str]:
    """scp each filename from remote_dir/ → local_dir/. Returns None on success
    or error string (only fails on hard ssh/scp error; missing files are
    tolerated since caller's existence check covers them)."""
    for fname in filenames:
        rc = subprocess.call(
            ["scp", "-q", "-o", "StrictHostKeyChecking=no",
             "-o", "UserKnownHostsFile=/dev/null",
             f"{a3_user}@{a3_host}:{remote_dir}/{fname}",
             str(local_dir / fname)],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        )
        # Don't hard-fail on per-file errors (runner may have produced a
        # subset); caller's .exists() check is the authoritative gate.
        _ = rc
    return None


def format_block_message(op: str, rep: O25A3Report) -> str:
    """Human-readable block message when verdict != READY*."""
    lines = [
        f"[phase_o25_a3_ref] op={op} verdict={rep.verdict}",
    ]
    for err in rep.errors:
        lines.append(f"  ERROR: {err}")
    for rec in rep.recommendations:
        lines.append(f"  → {rec}")
    if rep.peer_op_dependencies:
        lines.append(
            f"  NOTE: this op depends on peer op(s): "
            f"{', '.join(rep.peer_op_dependencies)}. "
            f"Cross-op router edits may be required (see KB W9)."
        )
    return "\n".join(lines)
